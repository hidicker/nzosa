/**
 * A fingerprint for a return's figures: printed with it, and worked out again
 * from the books whenever asked, so a printed copy can be checked against
 * them. A copy whose fingerprint is not what the books give now has had a
 * figure changed -- on paper, or in the books since it was printed.
 *
 * Tamper-evident, not tamper-proof: anybody with this code can make a
 * fingerprint for any figures. What it catches is a figure changed by hand,
 * or books changed after a return was printed from them.
 */

