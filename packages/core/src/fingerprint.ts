/** SHA-256 of a text's UTF-8 bytes, as lower-case hex. */
export function sha256Hex(text: string): string {
  const data = new TextEncoder().encode(text);
  const bitLength = data.length * 8;
  const padded = new Uint8Array(Math.ceil((data.length + 9) / 64) * 64);
  padded.set(data);
  padded[data.length] = 0x80;
  const view = new DataView(padded.buffer);
  view.setUint32(padded.length - 8, Math.floor(bitLength / 0x100000000));
  view.setUint32(padded.length - 4, bitLength >>> 0);
  const h = new Uint32Array([0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19]);
  const w = new Uint32Array(64);
  const rotr = (x: number, n: number): number => (x >>> n) | (x << (32 - n));
  for (let offset = 0; offset < padded.length; offset += 64) {
    for (let i = 0; i < 16; i += 1) w[i] = view.getUint32(offset + i * 4);
    for (let i = 16; i < 64; i += 1) {
      const a = w[i - 15] ?? 0;
      const b = w[i - 2] ?? 0;
      const s0 = rotr(a, 7) ^ rotr(a, 18) ^ (a >>> 3);
      const s1 = rotr(b, 17) ^ rotr(b, 19) ^ (b >>> 10);
      w[i] = ((w[i - 16] ?? 0) + s0 + (w[i - 7] ?? 0) + s1) >>> 0;
    }
    let [a, b, c, d, e, f, g, hh] = [h[0] ?? 0, h[1] ?? 0, h[2] ?? 0, h[3] ?? 0, h[4] ?? 0, h[5] ?? 0, h[6] ?? 0, h[7] ?? 0];
    for (let i = 0; i < 64; i += 1) {
      const t1 = (hh + (rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25)) + ((e & f) ^ (~e & g)) + (K[i] ?? 0) + (w[i] ?? 0)) >>> 0;
      const t2 = ((rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22)) + ((a & b) ^ (a & c) ^ (b & c))) >>> 0;
      hh = g;
      g = f;
      f = e;
      e = (d + t1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) >>> 0;
    }
    const add = [a, b, c, d, e, f, g, hh];
    for (let i = 0; i < 8; i += 1) h[i] = ((h[i] ?? 0) + (add[i] ?? 0)) >>> 0;
  }
  return [...h].map((x) => x.toString(16).padStart(8, "0")).join("");
}

/**
 * The fingerprint of a return: what it is, whose, the period, and every box
 * with its amount in cents. Sixteen characters in fours, which is enough to
 * catch a changed figure and short enough to read off paper and type.
 */
export function returnFingerprint(
  what: string,
  period: { from: string; to: string },
  boxes: readonly { box: string; amount: number | string }[],
  whose = "",
): string {
  const text = [
    "nzosa-return-v1",
    what.trim(),
    whose.trim(),
    period.from,
    period.to,
    ...boxes.map((b) => `${b.box.trim()}=${typeof b.amount === "number" ? Math.round(b.amount) : b.amount.trim()}`),
  ].join("\n");
  return sha256Hex(text).slice(0, 16).toUpperCase().replace(/(.{4})(?!$)/g, "$1-");
}

/** Whether a fingerprint typed in is this one, whatever its spacing, dashes or case. */
export function sameFingerprint(typed: string, fingerprint: string): boolean {
  const tidy = (t: string): string => t.toUpperCase().replace(/[^0-9A-F]/g, "");
  return tidy(typed) !== "" && tidy(typed) === tidy(fingerprint);
}
