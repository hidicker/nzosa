for (const [frequency, rows] of Object.entries(SAMPLE)) {
  test(`ATO Schedule 8 sample data, ${frequency} pays from 1 July 2026`, () => {
    const wrong = [];
    for (const [pay, claimed, notClaimed] of rows) {
      const got = [auSchedule8(pay, frequency, true, "2026-08-31"), auSchedule8(pay, frequency, false, "2026-08-31")];
      if (got[0] !== claimed || got[1] !== notClaimed) {
        wrong.push(`${pay / 100}: ATO ${claimed / 100}/${notClaimed / 100}, NZOSA ${got.map((c) => c / 100).join("/")}`);
      }
    }
    assert.deepEqual(wrong, []);
  });
}
